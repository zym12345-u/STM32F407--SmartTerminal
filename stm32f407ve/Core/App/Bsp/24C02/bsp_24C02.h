/* bsp_24C02.h
 * 板载 24C02 EEPROM 驱动接口：初始化探测、任意地址读、页写(自动分页)、上电自检。
 * 硬件：与 BH1750 共用 I2C1(PB6/PB7)，7 位地址 0x50(A2/A1/A0 全接地)，256 字节。
 */
#ifndef __BSP_24C02_H
#define __BSP_24C02_H

#include "stm32f4xx_hal.h"


/**
  * 功    能：初始化 24C02——先确保 I2C1 总线就绪，再探测器件是否在位
  * 参    数：无
  * 返 回 值：0 = 器件在位可用；1 = 无应答(没焊/地址错/总线坏)
  * 补    充：上电自检(AT24C02_SELFTEST=1 时)会对保留区 0xF8~0xFF 做
  *            一次写+读回验证并打印结果。该页专用于自检/出厂标志，
  *            不要拿来存业务数据。
  */
uint8_t AT24C02_Init(void);


/**
  * 功    能：从任意存储地址开始读若干字节(随机读 + 顺序读)
  * 参    数：memAddr 起始存储地址 0x00~0xFF；buf 接收缓冲；num 字节数 1~256
  * 返 回 值：0 = 成功；1 = 参数越界或总线失败
  * 补    充：一次事务完成(锁内)。内部用 RESTART：先"写"memAddr(不 STOP)转读，
  *            连续收 num 字节，最后 1 字节回 NACK。读任意长度都不会碰页边界——
  *            【读没有页的概念】，地址在 256B 内自动回绕；只有"写"才受页限制。
  */
uint8_t AT24C02_ReadBytes(uint8_t memAddr, uint8_t *buf, uint16_t num);


/**
  * 功    能：向任意存储地址写若干字节(自动按 8 字节页分段的页写)
  * 参    数：memAddr 起始存储地址 0x00~0xFF；buf 待写数据；num 字节数 1~256
  * 返 回 值：0 = 全部写完；1 = 参数越界或总线失败或写超时
  * 补    充：调用方只需给任意起始地址+长度，分页由本函数处理。
  *            跨页处自动 STOP → 等写周期(ACK 轮询) → 重新 START 写下一页。
  *            典型耗时 = (num/8 向上取整) × 约 5ms 写周期。
  */
uint8_t AT24C02_WriteBytes(uint8_t memAddr, const uint8_t *buf, uint16_t num);


#endif /* __BSP_24C02_H */
